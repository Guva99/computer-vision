"""
Уровни опасности и решающее правило по дистанции (формула 13 статьи).

Вынесено в ядро отдельным модулем: это та самая функция, по которой система
решает останавливать робота, и она обязана быть проверяемой без камеры, окон и
контроллера. Пороги приходят аргументами — их источник (AppConfig) ядро не знает.
"""

SAFE = "SAFE"
WARN = "WARN"
DANGER = "DANGER"

# Порядок строгости: сравнение уровней между объектами кадра и дебаунс останова.
LEVEL_ORDER = {SAFE: 0, WARN: 1, DANGER: 2}


def classify_level(dist_m: float, warn_m: float, danger_m: float) -> str:
    """Уровень по минимальной дистанции до манипулятора.

    Границы включающие: ровно на пороге считаем более опасный уровень — для
    системы безопасности ошибка в эту сторону дешевле.
    """
    if dist_m <= danger_m:
        return DANGER
    if dist_m <= warn_m:
        return WARN
    return SAFE


def worst(level_a: str, level_b: str) -> str:
    """Консервативное слияние двух уровней — берём более опасный.

    Нужно там, где решений несколько: объекты в кадре, а в дальнейшем (шаг S3.5)
    быстрый и медленный контуры и несколько камер.
    """
    return level_a if LEVEL_ORDER.get(level_a, 0) >= LEVEL_ORDER.get(level_b, 0) else level_b
